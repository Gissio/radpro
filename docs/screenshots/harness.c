bool setDeviceTime(uint32_t value)
{
    rtcBase = value - (double)currentTick / SYSTICK_FREQUENCY;

    return true;
}

uint32_t getDeviceTime(void)
{
    return (uint32_t)(rtcBase + (double)currentTick / SYSTICK_FREQUENCY);
}

